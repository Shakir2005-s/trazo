import type { Scene } from "../scene.js";
import { VERSION } from "../version.js";
import { INTER_400_WOFF2_BASE64, INTER_600_WOFF2_BASE64 } from "./generated/font.js";
import { ICONS } from "./generated/icons.js";
import { escapeXml, renderSvg } from "./svg.js";
import { pageCss } from "./theme.js";
import { VIEWER_SCRIPT } from "./viewer.js";

const ATTRIBUTION = `Generated by trazo ${VERSION}. Icons: Lucide (ISC License), portions derived from Feather (MIT License, Copyright (c) 2013-present Cole Bemis). Font: Inter (SIL Open Font License 1.1, Copyright 2016 The Inter Project Authors).`;

const button = (id: string, label: string, icons: string[]) =>
  `<button type="button" id="${id}" aria-label="${label}" title="${label}">${icons
    .map(
      (name) =>
        `<svg class="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] ?? ""}</svg>`,
    )
    .join("")}</button>`;

export function renderHtml(scene: Scene): string {
  const title = escapeXml(scene.title);
  const desc = scene.description ? `\n    <p class="desc">${escapeXml(scene.description)}</p>` : "";
  return `<!doctype html>
<!-- ${ATTRIBUTION} -->
<html lang="en" data-theme="${scene.theme}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="trazo ${VERSION}">
<title>${title}</title>
<style>${pageCss(INTER_400_WOFF2_BASE64, INTER_600_WOFF2_BASE64)}</style>
</head>
<body>
<header>
  <div class="heading">
    <h1>${title}</h1>${desc}
  </div>
  <div class="actions">
    <div class="group">
      ${button("zoom-out", "Zoom out", ["zoom-out"])}
      ${button("zoom-in", "Zoom in", ["zoom-in"])}
      ${button("fit", "Fit to screen", ["focus"])}
    </div>
    <div class="group">
      ${button("save-svg", "Download SVG", ["file-code"])}
      ${button("save-png", "Download PNG", ["file-image"])}
    </div>
    <div class="group">
      ${button("fullscreen", "Enter full screen", ["maximize", "minimize"])}
      ${button("theme", scene.theme === "dark" ? "Switch to light theme" : "Switch to dark theme", ["sun", "moon"])}
    </div>
  </div>
</header>
<main>
  <div class="stage" tabindex="0" aria-label="Diagram, use arrow keys to pan and plus or minus to zoom">
${renderSvg(scene)}
  </div>
</main>
<footer class="credit"><a href="https://github.com/heidenber/trazo" target="_blank" rel="noopener noreferrer">Made with trazo</a></footer>
<div class="tip" id="tip" role="tooltip"></div>
<script>${VIEWER_SCRIPT}</script>
</body>
</html>
`;
}
