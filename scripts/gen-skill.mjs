// Builds skill/AGENTS.md (the Codex form of the skill) from skill/SKILL.md:
// frontmatter removed, description kept as the intro, wrapped in markers so
// the block can be found and removed from a user's AGENTS.md.
import { readFileSync } from "node:fs";
import { emit } from "./lib.mjs";

const source = readFileSync("skill/SKILL.md", "utf8").replace(/\r\n/g, "\n");
const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(source);
if (!match) {
  console.error("error: skill/SKILL.md has no frontmatter");
  process.exit(1);
}

const field = (name) => {
  const line = match[1].split("\n").find((l) => l.startsWith(`${name}:`));
  return line ? line.slice(name.length + 1).trim() : "";
};
if (field("name") !== "trazo") {
  console.error("error: skill/SKILL.md must set name: trazo");
  process.exit(1);
}

const out = `<!-- Generated by scripts/gen-skill.mjs from skill/SKILL.md. Do not edit. -->
<!-- trazo:start -->
## trazo

${field("description")}

${match[2].trim()}
<!-- trazo:end -->
`;

emit("skill/AGENTS.md", out);
