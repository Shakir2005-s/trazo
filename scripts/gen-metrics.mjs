// Extracts per-character advance widths from the Inter files we embed, so
// labels can be measured in Node exactly as the browser will draw them.
// Kerning and ligatures are disabled in the rendered SVG to keep this exact.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import opentype from "opentype.js";
import { emit, packageDir, packageInfo } from "./lib.mjs";

const FIRST = 0x20;
const LAST = 0xff;
const files = join(packageDir("@fontsource/inter"), "files");

function load(weight) {
  const data = readFileSync(join(files, `inter-latin-${weight}-normal.woff`));
  return opentype.parse(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength));
}

function widths(font) {
  const out = [];
  for (let cp = FIRST; cp <= LAST; cp++) {
    const glyph = font.charToGlyph(String.fromCodePoint(cp));
    out.push(glyph.index === 0 ? 0 : glyph.advanceWidth);
  }
  return out;
}

const regular = load(400);
const semibold = load(600);
const version = packageInfo("@fontsource/inter").version;

const lines = [
  "// SPDX-License-Identifier: Apache-2.0",
  "// Generated by scripts/gen-metrics.mjs from @fontsource/inter " + version + ". Do not edit.",
  "// Inter is licensed under the SIL Open Font License 1.1; see THIRD_PARTY_NOTICES.md.",
  "",
  `export const UNITS_PER_EM = ${regular.unitsPerEm};`,
  `export const ASCENDER = ${regular.ascender};`,
  `export const DESCENDER = ${regular.descender};`,
  `export const FIRST_CODE_POINT = ${FIRST};`,
  "",
  "/** Advance widths for U+0020..U+00FF; 0 means the glyph is missing. */",
  `export const ADVANCES_400: readonly number[] = [${widths(regular).join(", ")}];`,
  `export const ADVANCES_600: readonly number[] = [${widths(semibold).join(", ")}];`,
  "",
];

emit("src/text/generated/metrics.ts", lines.join("\n"));
